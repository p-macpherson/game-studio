// The studio's colour themes. Each fills the same slots; styles.css derives tints (error bar, selection, highlights)
// from them. Palettes from their projects: catppuccin.com/palette, sainnhe/everforest's palette.md, draculatheme.com,
// nordtheme.com, morhetz/gruvbox, tokyo-night, ethanschoonover.com/solarized, rosepinetheme.com, Atom's One Dark.

export interface ThemeColors {
	/** Deepest background: viewports, thumbnails, the console. */
	sunken: string;
	/** The page. */
	bg: string;
	/** Raised areas: hover, cards. */
	panel: string;
	/** More raised: buttons, the selection. */
	panel2: string;
	border: string;
	text: string;
	/** Secondary text. */
	muted: string;
	/** Links, focus, highlights. */
	accent: string;
	/** Primary buttons, with `onAccent` text on them. */
	accent2: string;
	onAccent: string;
	green: string;
	yellow: string;
	red: string;
	purple: string;
	blue: string;
	orange: string;
}

export interface Theme {
	id: string;
	name: string;
	kind: "light" | "dark";
	/** For grouping in Settings ("Catppuccin"). */
	family: string;
	colors: ThemeColors;
}

const catppuccin = (
	id: string,
	name: string,
	kind: "light" | "dark",
	c: { crust: string; mantle: string; base: string; surface0: string; surface1: string; text: string; subtext0: string; blue: string; lavender: string; green: string; yellow: string; red: string; mauve: string; peach: string },
): Theme => ({
	id,
	name,
	kind,
	family: "Catppuccin",
	colors: {
		sunken: c.crust,
		bg: c.base,
		panel: c.mantle,
		panel2: c.surface0,
		border: c.surface1,
		text: c.text,
		muted: c.subtext0,
		accent: c.blue,
		accent2: c.blue,
		onAccent: kind === "dark" ? c.crust : c.base,
		green: c.green,
		yellow: c.yellow,
		red: c.red,
		purple: c.mauve,
		blue: c.lavender,
		orange: c.peach,
	},
});

