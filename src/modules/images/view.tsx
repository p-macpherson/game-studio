// The Images section: every picture in assets/images/ (concept art, maps, UI mockups…) in the project's own folders,
// shown large with how it was made, plus adding your own files, generating new ones, and asking the Concept Artist.
import { useEffect, useRef, useState } from "react";
import { useShallow } from "zustand/react/shallow";
import { studioFile } from "../../renderer/api";
import { useStudio } from "../../renderer/store";
import { AssetBrowser, type AssetContentProps } from "../../renderer/views/AssetBrowser";
import { runInWorktree } from "../../renderer/workspace";
import { IMAGE_ASPECTS, IMAGES_DIR, type ImageAspect, type ImageInfo, imageInfo } from "../../shared/images";
import type { AssetSummary, ModuleInfo } from "../../shared/modules";

/** The folder an image is in, under assets/images/ ("" at the top). */
const folderOf = (path: string) => {
	const rel = path.slice(IMAGES_DIR.length + 1);
	return rel.includes("/") ? rel.slice(0, rel.lastIndexOf("/")) : "";
};

/** A picked or dropped file as add_images takes it. */
async function fileParams(f: File): Promise<{ name: string; data: string }> {
	const bytes = new Uint8Array(await f.arrayBuffer());
	let bin = "";
	for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
	return { name: f.name || "pasted.png", data: btoa(bin) };
}

const version = (a: AssetSummary) => `${a.updatedAt ?? ""}:${a.excerpt}`;

export function ImagesView({ module }: { module: ModuleInfo }) {
	const [creating, setCreating] = useState<{ folder: string } | null>(null);
	const { showError } = useStudio(useShallow((s) => ({ showError: s.showError })));
	const remove = async (asset: AssetSummary) => {
		if (!confirm(`Delete ${asset.path}? (Undo brings it back until the worktree is saved.)`)) return;
		try {
			await runInWorktree(`Images: ${asset.title}`, "delete_image", { path: asset.path });
			useStudio.setState((s) => ({ assetsVersion: s.assetsVersion + 1 }));
		} catch (err) {
			showError(err);
		}
	};
	return (
		<>
			<AssetBrowser
				module={module}
				newLabel="+ New image"
				onNew={() => setCreating({ folder: "" })}
				modifyLabel="Change"
				modifyPlaceholder="What should change? (The Concept Artist makes a new version beside it, or variations.)"
				emptyText="No images yet: add your own, generate one, or ask the Concept Artist for concept art, a map or a UI mockup."
				itemPreview={(a, checkout) => (a.change === "deleted" ? null : <img className="image-thumb" src={studioFile(checkout, a.path, version(a))} alt="" loading="lazy" />)}
				actions={(asset) =>
					asset.change === "deleted" ? null : (
						<>
							<button onClick={() => setCreating({ folder: folderOf(asset.path) })} title="Add or generate images in this image's folder" data-testid="images-add-here">
								+ Add here
							</button>
							<button className="ghost" onClick={() => void remove(asset)} data-testid="image-delete">
								Delete
							</button>
						</>
					)
				}
				content={(props) => <ImageDetail key={`${props.asset.path}:${props.checkout ?? ""}`} {...props} />}
			/>
			{creating && <NewImagesDialog folder={creating.folder} module={module} onClose={() => setCreating(null)} />}
		</>
	);
}

function ImageDetail({ asset, assets, checkout }: AssetContentProps) {
	const showImages = useStudio((s) => s.showImages);
	const src = studioFile(checkout, asset.path, version(asset));
	const [info, setInfo] = useState<ImageInfo | null>(null);
	// How it was made lives inside the file: read its first bytes in the page.
	useEffect(() => {
		let live = true;
		fetch(src)
			.then((r) => r.arrayBuffer())
			.then((b) => live && setInfo(imageInfo(new Uint8Array(b))))
			.catch(() => live && setInfo(null));
		return () => {
			live = false;
		};
	}, [src]);
	if (asset.change === "deleted") return <p className="muted">This worktree removes this image.</p>;
	// The viewer steps through the images in the same folder.
	const siblings = assets.filter((a) => a.change !== "deleted" && folderOf(a.path) === folderOf(asset.path));
	const open = () =>
		showImages(
			siblings.map((a) => ({ src: studioFile(checkout, a.path, version(a)), label: a.path })),
			Math.max(0, siblings.findIndex((a) => a.path === asset.path)),
		);
	const record = info?.record;
	return (
		<div className="col image-detail" data-testid="image-detail">
			<button className="image-large" onClick={open} title="Open full size (← → step through this folder)">
				<img src={src} alt={asset.title} data-testid="image-large" />
			</button>
			<div className="muted small" data-testid="image-facts">
				{asset.excerpt.split(" · ").slice(0, 2).join(" · ")}
			</div>
			{record ? (
				<div className="image-record col" data-testid="image-record">
					<div className="small muted">
						Generated by {record.model ?? "an image model"}
						{record.seed !== undefined ? `, seed ${record.seed}` : ""}
						{record.at ? `, ${new Date(record.at).toLocaleString()}` : ""}
					</div>
					<p>{record.prompt}</p>
					{record.references?.length ? <div className="small muted">From: {record.references.join(", ")}</div> : null}
				</div>
			) : info?.text.Description ? (
				<p className="image-record">{info.text.Description}</p>
			) : null}
		</div>
	);
}

function NewImagesDialog({ folder: startFolder, module, onClose }: { folder: string; module: ModuleInfo; onClose(): void }) {
	const { showAsset, showError, openNewSession } = useStudio(useShallow((s) => ({ showAsset: s.showAsset, showError: s.showError, openNewSession: s.openNewSession })));
	const [folder, setFolder] = useState(startFolder);
	const [prompt, setPrompt] = useState("");
	const [name, setName] = useState("");
	const [count, setCount] = useState(1);
	const [aspect, setAspect] = useState<ImageAspect>("square");
	const [busy, setBusy] = useState<string | null>(null);
	const picker = useRef<HTMLInputElement>(null);
	const cleanFolder = folder.trim().replace(/^\/+|\/+$/g, "");
	const folderOk = !cleanFolder || /^[a-z0-9]+(-[a-z0-9]+)*(\/[a-z0-9]+(-[a-z0-9]+)*)*$/.test(cleanFolder);
	const suggested = prompt.trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").split("-").slice(0, 4).join("-");
	const finalName = name.trim() || suggested;
	const done = (paths: string[], checkout: string) => {
		useStudio.setState((s) => ({ assetsVersion: s.assetsVersion + 1 }));
		if (paths[0]) showAsset({ path: paths[0], checkout });
		onClose();
	};
	const add = async (files: File[]) => {
		const list = files.filter((f) => f.type.startsWith("image/"));
		if (!list.length) return;
		setBusy(`Adding ${list.length === 1 ? list[0].name : `${list.length} images`}…`);
		try {
			const { result, checkout } = await runInWorktree("Images", "add_images", { folder: cleanFolder, files: await Promise.all(list.map(fileParams)) });
			done((result as { images: string[] }).images, checkout);
		} catch (err) {
			showError(err);
			setBusy(null);
		}
	};
	const generate = async () => {
		setBusy(count === 1 ? "Generating the image…" : `Generating ${count} images…`);
		try {
			const path = cleanFolder ? `${cleanFolder}/${finalName}` : finalName;
			const { result, checkout } = await runInWorktree(`Image ${path}`, "generate_image", { path, prompt: prompt.trim(), count, aspect });
			done((result as { images: string[] }).images, checkout);
		} catch (err) {
			showError(err);
			setBusy(null);
		}
	};
	const ask = () => {
		onClose();
		openNewSession({
			agentType: module.agentType,
			target: "project",
			context: cleanFolder ? `Images in ${IMAGES_DIR}/${cleanFolder}/` : undefined,
			prompt: prompt.trim() ? `${prompt.trim()}${cleanFolder ? `\n\nPut it in ${IMAGES_DIR}/${cleanFolder}/.` : ""}` : undefined,
			placeholder: "What should it show? Concept art, a map design, a UI mockup… and what it's for.",
		});
	};
	return (
		<div className="modal-backdrop">
			<div className="modal col" data-testid="new-images">
				<h2>New images</h2>
				<label className="field">
					<span>Folder in {IMAGES_DIR}/</span>
					<input value={folder} onChange={(e) => setFolder(e.target.value)} placeholder="e.g. concept/characters, maps, ui/mockups (empty: the top)" data-testid="new-images-folder" />
					{!folderOk && <small className="msg error small">Lower-case words with hyphens, "/" between folders.</small>}
				</label>
				<div className="row">
					<button onClick={() => picker.current?.click()} disabled={!!busy || !folderOk} data-testid="new-images-files">
						Add files…
					</button>
					<span className="muted small grow">PNG, JPEG, WebP or GIF, copied as they are.</span>
				</div>
				<input ref={picker} type="file" accept="image/png,image/jpeg,image/webp,image/gif" multiple hidden onChange={(e) => void add([...(e.target.files ?? [])])} />
				<hr />
				<label className="field">
					<span>Or describe one to generate</span>
					<textarea
						rows={3}
						value={prompt}
						onChange={(e) => setPrompt(e.target.value)}
						placeholder="Top-down map of a small fishing village on a cliff, hand-drawn ink and watercolour, labelled docks, market and lighthouse"
						data-testid="new-images-prompt"
					/>
					<small className="muted">Used as written: say what it shows, the view and the style.</small>
				</label>
				<div className="row">
					<label className="field grow">
						<span>Name</span>
						<input value={name} onChange={(e) => setName(e.target.value)} placeholder={suggested || "fishing-village-map"} data-testid="new-images-name" />
					</label>
					<label className="field">
						<span>Shape</span>
						<select value={aspect} onChange={(e) => setAspect(e.target.value as ImageAspect)}>
							{Object.entries(IMAGE_ASPECTS).map(([k, [w, h]]) => (
								<option key={k} value={k}>
									{k} ({w}×{h})
								</option>
							))}
						</select>
					</label>
					<label className="field">
						<span>How many</span>
						<select value={count} onChange={(e) => setCount(Number(e.target.value))}>
							{[1, 2, 4].map((n) => (
								<option key={n}>{n}</option>
							))}
						</select>
					</label>
				</div>
				{busy && <div className="muted small" data-testid="new-images-busy">{busy}</div>}
				<div className="row">
					<button className="ghost" onClick={ask} disabled={!!busy} title="An agent makes it, iterates, and files it" data-testid="new-images-ask">
						Ask the Concept Artist…
					</button>
					<span className="grow" />
					<button onClick={onClose} disabled={!!busy}>
						Cancel
					</button>
					<button className="primary" onClick={() => void generate()} disabled={!!busy || !prompt.trim() || !folderOk || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(finalName)} data-testid="new-images-generate">
						Generate
					</button>
				</div>
			</div>
		</div>
	);
}
